"""LaTeX tables for the simulator section of the report (SPEC 0022).

    python -m src.sim.report_tables --out reports/tex/ [--allow-synthetic]

Writes one booktabs .tex file per table from the committed reports under reports/calibration/,
plus sim_tables.tex, which \\input{}s them all. Nothing is typed by hand: every number is read
from a csv (or the Current defaults block of the cross-race summary.md). Output is ASCII only.

Each file starts with a comment naming its source, sim_code_version and config_hash, taken from
the source's own stamps (a source that does not carry a stamp says so; nothing is invented).

Tables
  1 Spain replay summary and the position gate by pace term   2021_ESP_linear.csv, 2021_Spain_pace_gate.csv
  2 mid-race G by window and horizon bucket, posterior arm     cross_race/coverage_summary.csv, g_by_arm.csv
  3 stop-gain by window and k bucket with the decomposition    cross_race/stop_gain_summary.csv
  4 traffic arms (none, ghost, ghost_dirty), rejoin check       2021_04_spain_traffic.csv
  5 cross-race selection and the Current defaults block         cross_race/selection.csv, summary.md
  6 event-rate selection (forward folds)                        event_rates/*.csv
  7 race-pace prior candidates                                  fuel_prior/*.csv

A source whose run says PROVISIONAL gets that word in the caption. A synthetic source is refused
for tables 5-7 unless allow_synthetic is set (then it is captioned SYNTHETIC, layout preview only).
Tables 6 and 7 have no committed real source yet; they are written as a "source not committed
yet" placeholder, never with made-up numbers.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent.parent
CAL_DIR = ROOT / "reports" / "calibration"
OUT_DIR = ROOT / "reports" / "tex"
NOT_STAMPED = "not stamped in the source csv"


class SyntheticSourceRefused(RuntimeError):
    """A synthetic source was given to a table that refuses it without allow_synthetic."""


# --- LaTeX helpers ----------------------------------------------------------------------------
_ESC = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#", "$": r"\$",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(text) -> str:
    """Escape a string for LaTeX text. Raises on non-ASCII: nothing is silently dropped."""
    s = str(text).replace("`", "")
    s.encode("ascii")
    return "".join(_ESC.get(c, c) for c in s)


def num(v, digits=2) -> str:
    if v is None or (isinstance(v, float) and np.isnan(v)) or (not isinstance(v, str) and pd.isna(v)):
        return "--"
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "no"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return f"{float(v):.{digits}f}".replace("-", "$-$") if v < 0 else f"{float(v):.{digits}f}"
    return esc(v)


def ci(lo, hi, digits=2) -> str:
    return "--" if pd.isna(lo) or pd.isna(hi) else f"[{num(lo, digits)}, {num(hi, digits)}]"


def tabular(header, rows, align=None, small=True) -> str:
    align = align or "l" + "r" * (len(header) - 1)
    lines = [r"\small" if small else "", rf"\begin{{tabular}}{{{align}}}", r"\toprule",
             " & ".join(header) + r" \\", r"\midrule"]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(x for x in lines if x)


def table_env(label, caption, bodies, wide=False) -> str:
    if wide:
        bodies = ["\\resizebox{\\textwidth}{!}{%\n" + b + "\n}" for b in bodies]
    body = "\n\\medskip\n".join(bodies)
    return "\n".join([r"\begin{table}[htbp]", r"\centering", body, rf"\caption{{{caption}}}",
                      rf"\label{{tab:{label}}}", r"\end{table}", ""])


def provenance(source: str, sim_code_version, config_hash) -> str:
    return "\n".join([f"% source: {source}", f"% sim_code_version: {sim_code_version}",
                      f"% config_hash: {config_hash}", "% generated by python -m src.sim.report_tables; do not edit", ""])


def _stamp(df: pd.DataFrame, col: str) -> str:
    if col not in df or not df[col].notna().any():
        return NOT_STAMPED
    return ", ".join(sorted({str(v) for v in df[col].dropna()}))


def _rel(path: Path) -> str:
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


class Rendered:
    """One table: its file name, text (provenance comment included) and whether it is a placeholder."""

    def __init__(self, name, text, placeholder=False):
        self.name, self.text, self.placeholder = name, text, placeholder


# --- sources ----------------------------------------------------------------------------------
def _cross(cal: Path) -> Path:
    return cal / "cross_race"


def _run(cal: Path) -> dict:
    return json.loads((_cross(cal) / "run.json").read_text())


def cross_synthetic(cal: Path) -> bool:
    races = _run(cal).get("races", [])
    return any("synthetic" in r or str(r).startswith("2099_") for r in races)


def cross_provisional(cal: Path) -> bool:
    return "PROVISIONAL" in (_cross(cal) / "summary.md").read_text()


def cross_stamps(cal: Path, arm: str | None = None):
    run = _run(cal)
    arms = pd.read_csv(_cross(cal) / "arms.csv")
    if arm is not None and arm in set(arms["arm"]):
        h = ", ".join(sorted(arms.loc[arms["arm"] == arm, "config_hash"]))
    else:
        h = ", ".join(sorted(set(arms["config_hash"])))
    return run.get("sim_code_version", NOT_STAMPED), h


def _flag(cal: Path, synthetic_ok=False) -> str:
    """The caption prefix for a cross-race source."""
    if cross_synthetic(cal):
        return "SYNTHETIC (layout preview only). " if synthetic_ok else ""
    return "PROVISIONAL, one race. " if cross_provisional(cal) and len(_run(cal)["eligible"]) == 1 else (
        "PROVISIONAL. " if cross_provisional(cal) else "")


def _check_synthetic(cal: Path, table: int, allow: bool):
    if cross_synthetic(cal) and not allow:
        raise SyntheticSourceRefused(
            f"table {table}: {_rel(_cross(cal) / 'run.json')} lists a synthetic race; refused "
            "(pass --allow-synthetic for a layout preview)")


def current_defaults(cal: Path) -> pd.DataFrame:
    """The Current defaults block of cross_race/summary.md as a frame."""
    lines = (_cross(cal) / "summary.md").read_text().splitlines()
    start = next(i for i, ln in enumerate(lines) if ln.strip() == "## Current defaults")
    rows = []
    for ln in lines[start + 1:]:
        if ln.startswith("## "):
            break
        if ln.startswith("|"):
            rows.append([c.strip().replace("`", "") for c in ln.strip().strip("|").split("|")])
    rows = [r for r in rows if not set("".join(r)) <= set("-: ")]
    return pd.DataFrame(rows[1:], columns=rows[0])


# --- tables -----------------------------------------------------------------------------------
def table1(cal: Path = CAL_DIR) -> Rendered:
    lin = pd.read_csv(cal / "2021_ESP_linear.csv")
    gate = pd.read_csv(cal / "2021_Spain_pace_gate.csv")
    summary = [[num(len(lin), 0), num(lin["err_s"].abs().mean()), num(lin["err_s"].mean()),
                num(lin["err_pct"].abs().mean()), num(lin["err_offset_s"].abs().mean()),
                num(lin["err_green_s"].abs().mean())]]
    b1 = tabular(["drivers", "MAE (s)", "bias (s)", "MAE (\\%)", "MAE offset (s)", "MAE green (s)"], summary,
                 "rrrrrr")
    order = ["none", "practice", "team", "insample", "grid"]
    rows = []
    for p in order:
        r = []
        for mode in ("simulated_order", "vs_real"):
            g = gate[(gate["mode"] == mode) & (gate["pace"] == p)]
            r += [num(g["within_2_rate"].iloc[0]), num(g["mae_pos"].iloc[0]), num(g["exact_rate"].iloc[0])] if len(g) \
                else ["--"] * 3
        rows.append([esc(p), *r])
    b2 = tabular(["pace term", "sim: within 2", "sim: MAE pos", "sim: exact", "real: within 2", "real: MAE pos",
                  "real: exact"], rows, "lrrrrrr")
    cap = ("2021 Spanish GP replay of the simulator against the race result: totals per driver (top) and the "
           "finishing-position gate by pace term (bottom; sim = order of simulated totals, real = against the "
           "real finishing order).")
    src = "reports/calibration/2021_ESP_linear.csv; reports/calibration/2021_Spain_pace_gate.csv"
    head = provenance(src, f"{NOT_STAMPED} (2021_ESP_linear.csv); {_stamp(gate, 'sim_code_version')} (pace_gate)",
                      f"{NOT_STAMPED} (2021_ESP_linear.csv); {_stamp(gate, 'config_hash')} (pace_gate)")
    return Rendered("t1_spain_replay.tex", head + table_env("spain-replay", cap, [b1, b2]))


def table2(cal: Path = CAL_DIR, allow_synthetic=False) -> Rendered:
    cov = pd.read_csv(_cross(cal) / "coverage_summary.csv")
    g = pd.read_csv(_cross(cal) / "g_by_arm.csv")
    cov = cov[cov["arm"] == "posterior"]
    g = g[g["arm"] == "posterior"][["window", "horizon_bucket", "mae_offset_s"]]
    t = cov.merge(g, on=["window", "horizon_bucket"], how="left")
    rows = [[esc(r.window), num(int(r.horizon_bucket), 0), num(int(r.n), 0), num(r.mae_offset_s),
             num(r.coverage_68), num(r.coverage_90), num(r.coverage_raw_68), num(r.coverage_raw_90),
             num(r.mean_width_90_s)] for r in t.itertuples()]
    body = tabular(["window", "horizon", "n", "MAE offset (s)", "cov 68", "cov 90", "raw cov 68", "raw cov 90",
                    "width 90 (s)"], rows, "lrrrrrrrr")
    cap = (_flag(cal, allow_synthetic) + "Mid-race G from the posterior arm, by window and horizon bucket (laps "
           "ahead): MAE of the pace-corrected remaining time and the share of rows inside the 68 and 90 percent "
           "intervals, against the pace-corrected target and the raw one, with the mean 90 percent width.")
    ver, h = cross_stamps(cal, "posterior")
    head = provenance("reports/calibration/cross_race/coverage_summary.csv; "
                      "reports/calibration/cross_race/g_by_arm.csv", ver, h)
    return Rendered("t2_midrace_g.tex", head + table_env("midrace-g", cap, [body]))


def table3(cal: Path = CAL_DIR, allow_synthetic=False) -> Rendered:
    sg = pd.read_csv(_cross(cal) / "stop_gain_summary.csv")
    inc = current_defaults(cal).set_index("window")["incumbent"].to_dict()
    terms = ["t_base_old", "t_base_new", "t_wear_old", "t_wear_new", "t_hinge_old", "t_hinge_new", "t_fuel", "t_floor"]
    rows = []
    for w in ("to_snapshot", "full", "pre_race"):
        arm = inc.get(w)
        t = sg[(sg["window"] == w) & (sg["arm"] == arm)].sort_values("k_bucket")
        for r in t.itertuples():
            rows.append([esc(w), esc(arm), num(int(r.k_bucket), 0), num(int(r.n), 0), num(r.bias_s, 3),
                         num(r.mae_s, 3), ci(r.mae_ci_lo, r.mae_ci_hi), *[num(getattr(r, c), 3) for c in terms]])
    body = tabular(["window", "arm", "k", "n", "bias (s)", "MAE (s)", "MAE 95\\% CI",
                    *["$" + _term(c) + "$" for c in terms]], rows,
                   "llrrrrr" + "r" * len(terms))
    cap = (_flag(cal, allow_synthetic) + "Stop-gain error (predicted less real gain over a stop, seconds) by window "
           "and stops-so-far bucket k, for each window's incumbent arm, with the mean of each decomposition term "
           "(the terms sum to the bias).")
    ver, h = cross_stamps(cal)
    head = provenance("reports/calibration/cross_race/stop_gain_summary.csv; "
                      "reports/calibration/cross_race/summary.md (Current defaults)", ver, h)
    return Rendered("t3_stop_gain.tex", head + table_env("stop-gain", cap, [body], wide=True))


def _term(c: str) -> str:
    kind, _, age = c[2:].partition("_")
    return f"t_{{\\mathrm{{{kind}}}{',' + age if age else ''}}}"


def table4(cal: Path = CAL_DIR) -> Rendered:
    t = pd.read_csv(cal / "2021_04_spain_traffic.csv")
    arms = [("none", "none"), ("ghost", "ghost"), ("ghost_dirty", "ghost with dirty air")]
    rows = []
    for key, label in arms:
        sub = t[t["traffic"] == key]
        gate = sub[(sub["table"] == "gate") & (sub["mode"] == "simulated_order")].iloc[0]
        drv = sub[sub["table"] == "drivers"]
        pairs = sub[(sub["table"] == "pairs") & (sub["tie"].astype(str) != "True")]
        rej = sub[sub["table"] == "rejoin"]
        pe = rej["pos_err"].abs()
        agree = (pairs["sign_agree"].astype(str) == "True").mean() if len(pairs) else np.nan
        rows.append([esc(label), num(gate["within_2_rate"]), num(gate["mae_pos"]), num(drv["err_offset_s"].abs().mean()),
                     num(agree), num(len(rej), 0), num(pe.mean()), num((pe == 0).mean()), num((pe <= 1).mean())])
    body = tabular(["arm", "within 2", "MAE pos", "MAE offset (s)", "pair sign", "rejoins", "rejoin MAE pos",
                    "rejoin exact", "rejoin within 1"], rows, "lrrrrrrrr")
    cap = ("Traffic arms on the 2021 Spanish GP replay: the finishing-position gate (simulated order), "
           "driver-total error after the pace offset, team-mate sign agreement, and the rejoin check (predicted "
           "against real position at the first out-lap after each stop).")
    head = provenance("reports/calibration/2021_04_spain_traffic.csv", _stamp(t, "sim_code_version"),
                      _stamp(t[t["traffic"].isin([a for a, _ in arms])], "config_hash"))
    return Rendered("t4_traffic.tex", head + table_env("traffic", cap, [body]))


def table5(cal: Path = CAL_DIR, allow_synthetic=False) -> Rendered:
    _check_synthetic(cal, 5, allow_synthetic)
    sel = pd.read_csv(_cross(cal) / "selection.csv")
    rows = [[esc(r.stage), esc(r.window), esc(r.arm), esc(r.role), num(int(r.n_races), 0), num(r.g_mae),
             num(r.g_diff), ci(r.g_diff_lo, r.g_diff_hi), num(r.sg_mae), num(r.sg_diff), num(r.passes)]
            for r in sel.itertuples()]
    b1 = tabular(["stage", "window", "arm", "role", "races", "G MAE", "G diff", "G diff CI", "SG MAE", "SG diff",
                  "passes"], rows, "llllrrrrrrr")
    cur = current_defaults(cal)
    b2 = tabular([esc(c) for c in cur.columns], [[esc(v) for v in r] for r in cur.itertuples(index=False)], "l" * len(cur.columns))
    cap = (_flag(cal, allow_synthetic) + "Cross-race selection (held-out G, MAE of the pace-corrected remaining time "
           "in seconds at horizons 10-49; SG, stop-gain MAE in seconds; diff is the challenger less the incumbent) and the "
           "Current defaults block (bottom): each window's incumbent arm.")
    ver, h = cross_stamps(cal)
    head = provenance("reports/calibration/cross_race/selection.csv; "
                      "reports/calibration/cross_race/summary.md (Current defaults)", ver, h)
    return Rendered("t5_cross_race.tex", head + table_env("cross-race", cap, [b1, b2], wide=True))


def _generic(cal: Path, sub: str, name: str, label: str, caption: str, table_no: int, allow_synthetic) -> Rendered:
    """Tables 6 and 7: render the committed csv if one exists, else the explicit placeholder."""
    d = cal / sub
    files = sorted(d.glob("*.csv")) if d.is_dir() else []
    if not files:
        cap = f"{caption} Source not committed yet: no real run has produced {sub}/*.csv."
        body = r"\textit{source not committed yet}"
        head = provenance(f"none (reports/calibration/{sub}/*.csv not committed yet)", "n/a", "n/a")
        return Rendered(name, head + table_env(label, cap, [body]), placeholder=True)
    src = files[0]
    synthetic = "synthetic" in src.read_text().lower() or (d / "run.json").is_file() and \
        "synthetic" in (d / "run.json").read_text().lower()
    if synthetic and not allow_synthetic:
        raise SyntheticSourceRefused(f"table {table_no}: {_rel(src)} is synthetic; refused "
                                     "(pass --allow-synthetic for a layout preview)")
    df = pd.read_csv(src)
    rows = [[num(v) for v in r] for r in df.itertuples(index=False)]
    body = tabular(list(df.columns), rows, "l" * len(df.columns))
    flag = "SYNTHETIC (layout preview only). " if synthetic else ""
    head = provenance(_rel(src), _stamp(df, "sim_code_version"), _stamp(df, "config_hash"))
    return Rendered(name, head + table_env(label, flag + caption, [body], wide=True))


def table6(cal: Path = CAL_DIR, allow_synthetic=False) -> Rendered:
    return _generic(cal, "event_rates", "t6_event_rates.tex", "event-rates",
                    "Event-rate selection over forward folds.", 6, allow_synthetic)


def table7(cal: Path = CAL_DIR, allow_synthetic=False) -> Rendered:
    return _generic(cal, "fuel_prior", "t7_pace_prior.tex", "pace-prior",
                    "Race-pace prior candidates.", 7, allow_synthetic)


# --- driver -----------------------------------------------------------------------------------
def render_all(cal: Path = CAL_DIR, allow_synthetic=False):
    """([Rendered], [refusal messages]) for tables 1-7."""
    makers = [lambda: table1(cal), lambda: table2(cal, allow_synthetic), lambda: table3(cal, allow_synthetic),
              lambda: table4(cal), lambda: table5(cal, allow_synthetic), lambda: table6(cal, allow_synthetic),
              lambda: table7(cal, allow_synthetic)]
    done, refused = [], []
    for make in makers:
        try:
            done.append(make())
        except SyntheticSourceRefused as e:
            refused.append(str(e))
    return done, refused


def write(out: Path = OUT_DIR, cal: Path = CAL_DIR, allow_synthetic=False):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    done, refused = render_all(cal, allow_synthetic)
    for t in done:
        t.text.encode("ascii")
        (out / t.name).write_text(t.text)
    index = ["% sim_tables.tex: includes every generated simulator table.",
             "% needs \\usepackage{booktabs} and \\usepackage{graphicx}",
             "% generated by python -m src.sim.report_tables; do not edit", ""]
    index += [f"\\input{{{t.name[:-4]}}}" for t in done]
    (out / "sim_tables.tex").write_text("\n".join(index) + "\n")
    return done, refused


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m src.sim.report_tables", description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=str(OUT_DIR))
    ap.add_argument("--calibration-dir", default=str(CAL_DIR))
    ap.add_argument("--allow-synthetic", action="store_true",
                    help="render synthetic sources for tables 5-7 (layout previews only)")
    args = ap.parse_args(sys.argv[1:] if argv is None else argv)
    done, refused = write(Path(args.out), Path(args.calibration_dir), args.allow_synthetic)
    for t in done:
        print(f"{'placeholder' if t.placeholder else 'rendered   '} {t.name}")
    for msg in refused:
        print(f"REFUSED {msg}", file=sys.stderr)
    return 2 if refused else 0


if __name__ == "__main__":
    raise SystemExit(main())
